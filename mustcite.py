"""Load MustCite-Mini and score predictions the same way for everyone.

Do not edit this file. The numbers in your README must come from the evaluate_* functions here,
saved with save_results(), so that every student's numbers mean the same thing.

    from mustcite import load_task_a, evaluate_a, save_results

Split (fixed, by year): train = 2020-2023, val = 2024, test = 2025.
"""
import json
import time
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.metrics import (accuracy_score, confusion_matrix, f1_score, precision_score,
                             recall_score, roc_auc_score)

ROOT = Path(__file__).resolve().parent
DATA = ROOT / "data"
RESULTS = ROOT / "results"

VENUES = ["aaai", "acl", "cvpr", "iclr", "icml", "neurips"]
SPLITS = ("train", "val", "test")


def _read(name):
    for path in (DATA / f"{name}.csv.gz", DATA / f"{name}.csv"):
        if path.exists():
            df = pd.read_csv(path)
            text_cols = df.select_dtypes(include="object").columns
            df[text_cols] = df[text_cols].fillna("")
            return df
    raise FileNotFoundError(f"{name}.csv.gz not found in {DATA}")


def load_papers():
    """All 18,000 papers: paper_id, title, abstract, venue, year, split."""
    return _read("papers")


def load_citations():
    """All citation edges inside the set: citing_id, cited_id."""
    return _read("citations")


def _by_split(df):
    return tuple(df[df.split == s].reset_index(drop=True) for s in SPLITS)


# ---- Task A: which conference is this paper from? -----------------------------------------------

def load_task_a():
    """(train, val, test) DataFrames of papers. `label` is the venue's index in VENUES."""
    papers = load_papers()
    papers["label"] = papers.venue.map(VENUES.index)
    return _by_split(papers)


def evaluate_a(y_true, y_pred):
    """Accuracy, macro-F1 and the confusion matrix (rows: true venue, columns: predicted, in VENUES order).
    Labels may be venue names or indices into VENUES."""
    y_true = [VENUES.index(y) if isinstance(y, str) else int(y) for y in y_true]
    y_pred = [VENUES.index(y) if isinstance(y, str) else int(y) for y in y_pred]
    return {
        "accuracy": accuracy_score(y_true, y_pred),
        "macro_f1": f1_score(y_true, y_pred, average="macro"),
        "confusion_matrix": confusion_matrix(y_true, y_pred, labels=range(len(VENUES))).tolist(),
        "labels": VENUES,
    }


# ---- Task B: is this citation core, or background? ----------------------------------------------

def load_task_b():
    """(train, val, test) DataFrames of citation contexts. `label` is 1 for a core citation, 0 for background.
    A paper's citations are all in the split of that paper's year."""
    return _by_split(_read("contexts"))


def evaluate_b(y_true, y_score, threshold=0.5):
    """Precision, recall and F1 of the core class (label 1), and ROC-AUC.
    y_score: the predicted probability of label 1 (hard 0/1 predictions also work, with a less useful AUC).
    Choose the threshold on the validation set, then pass the same threshold for the test set."""
    y_true = np.asarray(y_true).astype(int)
    y_score = np.asarray(y_score, dtype=float)
    y_pred = (y_score >= threshold).astype(int)
    return {
        "precision": precision_score(y_true, y_pred, zero_division=0),
        "recall": recall_score(y_true, y_pred, zero_division=0),
        "f1": f1_score(y_true, y_pred, zero_division=0),
        "roc_auc": roc_auc_score(y_true, y_score),
        "threshold": threshold,
        "positive_rate": float(y_true.mean()),
    }


# ---- Task C: which papers will a new paper cite? ------------------------------------------------

def load_task_c(split):
    """The papers and citations you may use to predict the citations of `split` ("val" or "test").

    Returns a dict:
        queries     papers of the split's year (2024 for val, 2025 for test): rank candidates for each
        candidates  all papers from earlier years: the papers a query may cite
        known_edges citations made by the candidates: the graph you may use as input
    The citations made by the queries are the answers; evaluate_c() reads them, your model must not.
    """
    year = {"val": 2024, "test": 2025}[split]
    papers = load_papers()
    edges = load_citations()
    paper_year = dict(zip(papers.paper_id, papers.year))
    earlier = edges.citing_id.map(paper_year) < year
    return {
        "queries": papers[papers.year == year].reset_index(drop=True),
        "candidates": papers[papers.year < year].reset_index(drop=True),
        "known_edges": edges[earlier].reset_index(drop=True),
    }


def evaluate_c(split, ranking, k=10):
    """Recall@k and MRR.
    ranking: dict query paper_id -> list of candidate paper_ids, best first (the top 100 is enough).
    Only queries that cite at least one candidate are scored; a query missing from `ranking` scores 0."""
    year = {"val": 2024, "test": 2025}[split]
    papers = load_papers()
    edges = load_citations()
    paper_year = dict(zip(papers.paper_id, papers.year))
    answer = edges[(edges.citing_id.map(paper_year) == year) & (edges.cited_id.map(paper_year) < year)]
    answer = answer.groupby("citing_id").cited_id.apply(set)
    recalls, reciprocal_ranks = [], []
    for query, cited in answer.items():
        ranked = list(ranking.get(query, []))
        recalls.append(len(cited & set(ranked[:k])) / len(cited))
        first = next((i for i, c in enumerate(ranked) if c in cited), None)
        reciprocal_ranks.append(0.0 if first is None else 1.0 / (first + 1))
    return {f"recall@{k}": float(np.mean(recalls)), "mrr": float(np.mean(reciprocal_ranks)),
            "num_queries": len(answer)}


# ---- Saving results -----------------------------------------------------------------------------

def save_results(name, metrics, config=None):
    """Write results/<name>.json with the metrics, your settings and the time, and print the metrics.
    Commit these files: every number in your README must come from one of them."""
    RESULTS.mkdir(exist_ok=True)
    record = {"name": name, "time": time.strftime("%Y-%m-%d %H:%M:%S"), "config": config or {}, "metrics": metrics}
    path = RESULTS / f"{name}.json"
    path.write_text(json.dumps(record, indent=2))
    shown = {k: round(v, 4) if isinstance(v, float) else v for k, v in metrics.items()
             if k not in ("confusion_matrix", "labels")}
    print(f"{name}: {shown}  ->  {path.relative_to(ROOT)}")
    return path
